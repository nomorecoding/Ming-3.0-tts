"""Writes static/js/peaks.js: duration and waveform bars for every demo clip.

Run from the repository root after adding or replacing audio (needs ffmpeg):

    python3 scripts/peaks.py
"""
import array
import json
import math
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
BARS = 96
RATE = 8000


def decode(path):
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"],
        check=True, capture_output=True,
    ).stdout
    samples = array.array("h")
    samples.frombytes(raw)
    return samples


def bars(samples):
    step = max(1, len(samples) // BARS)
    levels = []
    for i in range(BARS):
        chunk = samples[i * step:(i + 1) * step]
        levels.append(math.sqrt(sum(s * s for s in chunk) / len(chunk)) if chunk else 0.0)
    top = max(levels) or 1.0
    return [max(4, round(100 * math.sqrt(v / top))) for v in levels]


def main():
    peaks = {}
    for path in sorted((ROOT / "static" / "audio").rglob("*.mp3")):
        samples = decode(path)
        key = path.relative_to(ROOT).as_posix()
        peaks[key] = {"d": round(len(samples) / RATE, 2), "p": bars(samples)}
    out = ROOT / "static" / "js" / "peaks.js"
    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, separators=(',', ':'))}" for k, v in peaks.items())
    out.write_text("// Generated by scripts/peaks.py. Do not edit by hand.\nwindow.PEAKS = {\n" + body + "\n};\n")
    print(f"wrote {len(peaks)} clips to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
